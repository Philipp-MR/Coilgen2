def default_parameters_for(example_name: str) -> dict:
    """Return the fallback parameter dictionary for an example script.

    The returned object is the shared default dictionary. Example scripts pass it
    to ``parse_example_parameters``, which copies values before merging them with
    user settings.
    """

    try:
        return DEFAULTS_BY_EXAMPLE[example_name]
    except KeyError as exc:
        known = ", ".join(sorted(DEFAULTS_BY_EXAMPLE))
        raise KeyError(f"No default parameters registered for {example_name!r}. Known examples: {known}") from exc
