from hashlib import sha256
import json
import shutil

import numpy as np
import pytest

from coilgen import CoilGenConfig, persistence, workflow
from coilgen.models import Mesh, TargetField
from coilgen.object_registry import register_in_memory_mesh, register_in_memory_target_field
from coilgen.research import storage


def source_tree(directory):
    package = directory / "coilgen"
    (package / "research").mkdir(parents=True)
    (package / "workflow.py").write_text("version = 1\n", encoding="utf-8")
    (package / "research" / "storage.py").write_text("version = 1\n", encoding="utf-8")
    return package


def test_recursive_source_digest_tracks_nested_code_names_and_ignores_generated_files(tmp_path):
    package = source_tree(tmp_path)
    first = persistence.source_digest(package)
    relocated = tmp_path / "other_checkout" / "coilgen"
    shutil.copytree(package, relocated)
    assert persistence.source_digest(relocated) == first

    (package / "research" / "storage.pyc").write_bytes(b"generated bytecode")
    (package / "README.md").write_text("documentation", encoding="utf-8")
    assert persistence.source_digest(package) == first

    nested = package / "research" / "storage.py"
    nested.write_text("version = 2\n", encoding="utf-8")
    second = persistence.source_digest(package)
    assert second != first
    renamed = nested.with_name("renamed.py")
    nested.rename(renamed)
    third = persistence.source_digest(package)
    assert third != second
    renamed.unlink()
    assert persistence.source_digest(package) != third


def test_case_and_research_identity_share_recursive_source_digest(tmp_path, monkeypatch):
    package = source_tree(tmp_path)
    monkeypatch.setattr(workflow, "__file__", str(package / "workflow.py"))
    monkeypatch.setattr(storage, "__file__", str(package / "research" / "storage.py"))
    first_identity, first_manifest = storage.request_identity({}, {})
    first_code = workflow._sweep_code_digest()
    assert first_manifest["source_sha256"] == first_code

    (package / "research" / "solver.py").write_text("tolerance = 1e-9\n", encoding="utf-8")
    second_identity, second_manifest = storage.request_identity({}, {})
    assert second_manifest["source_sha256"] == workflow._sweep_code_digest()
    assert second_manifest["source_sha256"] != first_code
    assert second_identity != first_identity


@pytest.mark.parametrize("failure", ["serialization", "write", "replace"])
def test_atomic_replacement_failure_preserves_previous_result(tmp_path, monkeypatch, failure):
    path = tmp_path / "result.json"
    persistence.atomic_json(path, {"accepted": True, "current_A": 2})
    original = path.read_bytes()
    modified = path.stat().st_mtime_ns
    if failure == "replace":

        def fail_replace(*_args):
            raise OSError("interrupted replace")

        monkeypatch.setattr(persistence.os, "replace", fail_replace)

    with pytest.raises((TypeError, OSError)):
        if failure == "serialization":
            persistence.atomic_json(path, {"unsupported": object()})
        elif failure == "write":
            with persistence.atomic_text_writer(path) as output:
                output.write('{"accepted":')
                raise OSError("interrupted write")
        else:
            persistence.atomic_json(path, {"accepted": False})
    assert path.read_bytes() == original
    assert path.stat().st_mtime_ns == modified
    assert list(tmp_path.iterdir()) == [path]


def test_file_digest_handles_multiple_blocks_and_storage_exports_remain_compatible(tmp_path):
    path = tmp_path / "mesh.bin"
    data = b"coilgen" * 200_000
    path.write_bytes(data)
    assert persistence.file_digest(path) == sha256(data).hexdigest()
    assert storage.file_digest is persistence.file_digest
    assert storage.atomic_json is persistence.atomic_json
    assert storage.json_value is persistence.json_value


@pytest.mark.parametrize("value", [float("nan"), float("inf"), np.array([float("-inf")])])
def test_input_identity_rejects_nonfinite_values_instead_of_conflating_them_with_null(tmp_path, value):
    with pytest.raises(ValueError):
        persistence.json_value(value, nonfinite="raise")
    with pytest.raises(ValueError):
        storage.request_identity({}, {"tolerance": value})
    with pytest.raises(ValueError):
        workflow._case_cache_path(tmp_path, 1, {"tolerance": value})
    assert workflow._case_cache_path(tmp_path, 1, {"tolerance": None}) is not None


def test_workflow_result_files_use_strict_json_without_changing_quality_or_timestamp(tmp_path):
    payload = {
        "run": {"status": "failed", "completed_at_utc": "2026-01-01T00:01:00Z"},
        "quality": {"status": "FAIL"},
        "metrics": {"coil_resistance_total_ohm": np.nan, "coil_inductance_same_current_H": np.inf},
    }
    summary = tmp_path / "summary.json"
    rows = tmp_path / "rows.jsonl"
    for writer in (workflow._write_json, workflow._write_run_record_json):
        writer(payload, summary)
        result = json.loads(summary.read_text(encoding="utf-8"))
        assert result["run"] == payload["run"]
        assert result["quality"] == payload["quality"]
        assert all(value is None for value in result["metrics"].values())
        assert summary.stat().st_size <= workflow.RUN_RECORD_MAX_SUMMARY_BYTES
    workflow._write_jsonl([payload], rows)
    workflow._append_jsonl(payload, rows)
    assert len(rows.read_text(encoding="utf-8").splitlines()) == 2
    for line in rows.read_text(encoding="utf-8").splitlines():
        assert "NaN" not in line and "Infinity" not in line
        assert json.loads(line)["quality"]["status"] == "FAIL"


def test_legacy_cache_write_is_atomic(tmp_path, monkeypatch):
    path = tmp_path / "case.json"
    workflow._write_json({"status": "success", "score": 1}, path)
    original = path.read_bytes()

    def fail_replace(*_args):
        raise OSError("disk unavailable")

    monkeypatch.setattr(persistence.os, "replace", fail_replace)
    with pytest.raises(OSError, match="disk unavailable"):
        workflow._write_json({"status": "success", "score": 2}, path)
    assert path.read_bytes() == original
    assert list(tmp_path.iterdir()) == [path]


@pytest.mark.parametrize("failure_count", [np.nan, np.inf, None])
def test_unavailable_failure_counts_never_make_cached_results_reusable(tmp_path, failure_count):
    path = tmp_path / "case.json"
    workflow._write_json({"status": "success", "failure_count": failure_count}, path)
    assert workflow._successful_cached_row(path) is None


def test_legacy_cache_fingerprints_in_memory_mesh_and_target_contents(tmp_path):
    mesh = Mesh(np.array([[0, 0, 0], [1, 0, 0], [0, 1, 0]]), np.array([[0, 1, 2]]))
    target = TargetField(
        coords=np.array([[0.1, 0.1, 0.2]]),
        b=np.array([[0, 0, 1e-5]]),
        weights=np.ones(1),
        suppressed=np.zeros(1, dtype=bool),
        target_field_group_inds=np.ones(1, dtype=int),
    )
    mesh_key = register_in_memory_mesh(mesh)
    target_key = register_in_memory_target_field(target)
    config = CoilGenConfig(coil_mesh_file=mesh_key, target_field_definition_file=target_key)
    first = workflow._sweep_input_digests(config, tmp_path)
    assert workflow._sweep_input_digests(config, tmp_path) == first
    mesh.vertices[1, 0] = 1.1
    register_in_memory_mesh(mesh, key=mesh_key)
    second = workflow._sweep_input_digests(config, tmp_path)
    assert second["coil_mesh_file"] != first["coil_mesh_file"]
    assert second["target_field_definition_file"] == first["target_field_definition_file"]
    target.b[0, 2] = 2e-5
    register_in_memory_target_field(target, key=target_key)
    third = workflow._sweep_input_digests(config, tmp_path)
    assert third["target_field_definition_file"] != second["target_field_definition_file"]
